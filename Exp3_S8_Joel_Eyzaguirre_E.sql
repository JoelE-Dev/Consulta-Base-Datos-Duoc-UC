CREATE OR REPLACE VIEW VW_AUM_MEDICO_X_CARGO AS
SELECT 
    M.RUT_MEDICO AS RUT_MEDICO,
    M.NOMBRE AS NOMBRE_MEDICO,
    C.NOMBRE AS CARGO,
    C.SUELDO_BASE AS SUELDO_BASE,
    ROUND(C.SUELDO_BASE * 1.15) AS SUELDO_AUMENTADO
FROM MEDICO M
JOIN CARGO C ON M.ID_CARGO = C.ID_CARGO
WHERE LOWER(C.NOMBRE) LIKE '%atencion%';

CREATE INDEX IDX_MEDICO_CARGO ON MEDICO(ID_CARGO);
CREATE INDEX IDX_CARGO_NOMBRE ON CARGO(NOMBRE);

