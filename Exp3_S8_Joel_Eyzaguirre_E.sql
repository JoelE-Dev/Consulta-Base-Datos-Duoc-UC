CREATE TABLE PREVISION (
    ID_PREVISION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50),
    CONSTRAINT PK_PREVISION PRIMARY KEY (ID_PREVISION)
);

CREATE TABLE PACIENTE (
    RUT_PACIENTE VARCHAR2(12),
    NOMBRE VARCHAR2(100),
    ID_PREVISION NUMBER,
    CONSTRAINT PK_PACIENTE PRIMARY KEY (RUT_PACIENTE),
    CONSTRAINT FK_PAC_PREV FOREIGN KEY (ID_PREVISION) REFERENCES PREVISION(ID_PREVISION)
