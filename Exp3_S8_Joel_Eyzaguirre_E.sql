CREATE OR REPLACE VIEW VW_RECALCULO_COSTOS AS
SELECT 
    P.RUT_PACIENTE AS RUT_PACIENTE,
    P.NOMBRE AS NOMBRE_PACIENTE,
    PR.NOMBRE AS PREVISION,
    TO_CHAR(C.FECHA_ATENCION,'DD-MM-YYYY HH24:MI') AS FECHA_ATENCION,
    C.COSTO AS COSTO_ORIGINAL,
    CASE 
        WHEN C.COSTO BETWEEN 15000 AND 25000 THEN ROUND(C.COSTO * 1.15)
        WHEN C.COSTO > 25000 THEN ROUND(C.COSTO * 1.20)
        ELSE C.COSTO
    END AS COSTO_RECALCULADO
FROM SYN_CONSULTA C
JOIN SYN_PACIENTE P ON C.RUT_PACIENTE = P.RUT_PACIENTE
JOIN SYN_PREVISION PR ON P.ID_PREVISION = PR.ID_PREVISION
WHERE EXTRACT(YEAR FROM C.FECHA_ATENCION) = EXTRACT(YEAR FROM SYSDATE) - 1
AND TO_NUMBER(TO_CHAR(C.FECHA_ATENCION,'HH24MI')) > 1715
AND PR.NOMBRE IN ('FONASA','ISAPRE');





