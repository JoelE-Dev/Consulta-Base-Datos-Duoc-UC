    NRO_TARJETA,
    TOTAL_CUOTAS,
    MONTO_TOTAL_TRANSA,
    FECHA_TRANSACCION,
    DIRECCION,
    MONTO_REAJUSTADO
)
SELECT
    SEQ_T_ANALISIS.NEXTVAL,
    T.NRO_TARJETA,
    TR.TOTAL_CUOTAS,
    TR.MONTO_TOTAL,
    TO_CHAR(TR.FECHA_TRANSACCION,'DD/MM/YYYY'),
    INITCAP(S.DIRECCION),
    ROUND
    (
        CASE
            WHEN TR.MONTO_TOTAL BETWEEN 200000 AND 300000
            THEN TR.MONTO_TOTAL * 1.05

            WHEN TR.MONTO_TOTAL BETWEEN 300001 AND 500000
            THEN TR.MONTO_TOTAL * 1.07

            ELSE TR.MONTO_TOTAL
        END
    )
FROM SYN_TARJETA T
JOIN SYN_TRANSACCION TR
ON T.NRO_TARJETA = TR.NRO_TARJETA
JOIN SYN_SUCURSAL S
ON TR.ID_SUCURSAL = S.ID_SUCURSAL
WHERE UPPER(S.DIRECCION) LIKE 'A%'
AND TR.MONTO_TOTAL >= 200000
ORDER BY T.NRO_TARJETA ASC, MONTO_REAJUSTADO DESC;

