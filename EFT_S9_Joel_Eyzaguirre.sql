CREATE TABLE DEUDOR (
    RUT_DEUDOR VARCHAR2(12),
    PNOMBRE VARCHAR2(50),
    APPATERNO VARCHAR2(50),
    APMATERNO VARCHAR2(50),
    TELEFONO VARCHAR2(20),
    ID_OCUPACION NUMBER,
    CONSTRAINT PK_DEUDOR PRIMARY KEY(RUT_DEUDOR),
    CONSTRAINT FK_DEUDOR_OCUP FOREIGN KEY(ID_OCUPACION)
    REFERENCES OCUPACION(ID_OCUPACION)
);

CREATE TABLE TARJETA_CREDITO (
    NRO_TARJETA VARCHAR2(30),
    RUT_DEUDOR VARCHAR2(12),
    CUPO_TOTAL NUMBER,
    CUPO_UTILIZADO NUMBER,
    CONSTRAINT PK_TARJETA PRIMARY KEY(NRO_TARJETA),
    CONSTRAINT FK_TARJETA_DEUDOR FOREIGN KEY(RUT_DEUDOR)
    REFERENCES DEUDOR(RUT_DEUDOR)
);

CREATE TABLE CUOTA (
    ID_CUOTA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NRO_TARJETA VARCHAR2(30),
    FECHA_VENCIMIENTO DATE,
    VALOR_CUOTA NUMBER,
    TOTAL_CUOTAS NUMBER,
    CONSTRAINT PK_CUOTA PRIMARY KEY(ID_CUOTA),
    CONSTRAINT FK_CUOTA_TARJETA FOREIGN KEY(NRO_TARJETA)
    REFERENCES TARJETA_CREDITO(NRO_TARJETA)
);

CREATE TABLE SUCURSAL (
    ID_SUCURSAL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DIRECCION VARCHAR2(150),
    CONSTRAINT PK_SUCURSAL PRIMARY KEY(ID_SUCURSAL)
);

CREATE TABLE TRANSACCION (
    ID_TRANSACCION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NRO_TARJETA VARCHAR2(30),
    ID_SUCURSAL NUMBER,
    FECHA_TRANSACCION DATE,
    MONTO_TOTAL NUMBER,
    TOTAL_CUOTAS NUMBER,
    CONSTRAINT PK_TRANSACCION PRIMARY KEY(ID_TRANSACCION),
    CONSTRAINT FK_TRANS_TARJETA FOREIGN KEY(NRO_TARJETA)
    REFERENCES TARJETA_CREDITO(NRO_TARJETA),
    CONSTRAINT FK_TRANS_SUCURSAL FOREIGN KEY(ID_SUCURSAL)
    REFERENCES SUCURSAL(ID_SUCURSAL)
);

