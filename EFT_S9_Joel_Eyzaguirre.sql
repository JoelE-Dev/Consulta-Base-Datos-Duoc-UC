--Crear vista de analisis de deudores

CREATE OR REPLACE VIEW VW_ANALISIS_DEUDORES_PERIODO AS
SELECT
    D.RUT_DEUDOR AS RUT_DEUDOR,
    INITCAP(D.PNOMBRE || ' ' || D.APPATERNO || ' ' || D.APMATERNO) AS NOMBRE_DEUDOR,
    MAX(C.TOTAL_CUOTAS) AS TOTAL_CUOTAS,
    ROUND(AVG(C.VALOR_CUOTA)) AS PROMEDIO_VALOR_CUOTAS,
    TO_CHAR(MIN(C.FECHA_VENCIMIENTO),'DD/MM/YYYY') AS FECHA_MAS_ANTIGUA,
    NVL(D.TELEFONO,'Sin Informacion') AS TELEFONO,
    UPPER(O.NOMBRE_OCUPACION) AS OCUPACION,
    (T.CUPO_TOTAL - T.CUPO_UTILIZADO) AS CUPO_DISP_COMPRA
FROM SYN_DEUDOR D
JOIN SYN_OCUPACION O
ON D.ID_OCUPACION = O.ID_OCUPACION
JOIN SYN_TARJETA T
ON D.RUT_DEUDOR = T.RUT_DEUDOR
JOIN SYN_CUOTA C
ON T.NRO_TARJETA = C.NRO_TARJETA
WHERE UPPER(O.NOMBRE_OCUPACION) <> 'INGENIERO'
AND EXTRACT(YEAR FROM C.FECHA_VENCIMIENTO) = EXTRACT(YEAR FROM SYSDATE)-1
GROUP BY
D.RUT_DEUDOR,
D.PNOMBRE,
D.APPATERNO,
D.APMATERNO,
D.TELEFONO,
O.NOMBRE_OCUPACION,
T.CUPO_TOTAL,
T.CUPO_UTILIZADO
HAVING ROUND(AVG(C.VALOR_CUOTA)) <
(
    SELECT MAX(PROMEDIO_GENERAL)
    FROM
    (
        SELECT ROUND(AVG(VALOR_CUOTA)) AS PROMEDIO_GENERAL
        FROM SYN_CUOTA
        GROUP BY NRO_TARJETA
    )
);

