--Crear tablas del sistema financiero

CREATE TABLE OCUPACION (
    ID_OCUPACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE_OCUPACION VARCHAR2(100),
    CONSTRAINT PK_OCUPACION PRIMARY KEY(ID_OCUPACION)
